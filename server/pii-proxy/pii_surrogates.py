"""Format-preserving fake values (surrogates) for the PII proxy.

Rationale (see issue #36): from a privacy point of view *which* email address the
model sees does not matter, only that it sees something that behaves like an
email address. A realistic fake keeps the model effective (it can reason about
domains, formats, lengths) while never carrying the real value, and - unlike an
opaque token - it is normal text that the model copies verbatim far more
reliably.

Every surrogate is:

* deterministic - same (kind, value) always yields the same fake, so multi-turn
  reasoning and prompt caching stay stable;
* shape-preserving - generated by kind, so an email stays an email, a 4-byte IP
  stays a private-range IP, a JWT still has three base64url segments;
* non-invertible on its own - the mapping lives only in the local vault, and the
  generator never reuses characters from the original value.

Fake domains use the RFC 2606 reserved domains on purpose: they look real to the
model without pointing at somebody's actual mailbox.
"""

from __future__ import annotations

import base64
import random
import re

FIRST_NAMES = [
    "alex", "jordan", "casey", "riley", "morgan", "taylor", "jamie", "robin",
    "avery", "quinn", "drew", "cameron", "dakota", "emerson", "finley",
    "harper", "kendall", "logan", "parker", "reese", "rowan", "sage", "sawyer",
]
LAST_NAMES = [
    "chen", "novak", "reyes", "patel", "kim", "silva", "muller", "okafor",
    "rossi", "tanaka", "ivanov", "garcia", "brooks", "nguyen", "schmidt",
    "ahmed", "cohen", "lopez", "wright", "haddad", "baker", "moreau",
]
FAKE_DOMAINS = ["example.com", "example.net", "example.org", "mail.example.com"]
USERNAMES = ["dev.user", "svc.account", "ops.team", "qa.bot", "admin.user", "etl.job"]

_UPPER = "ABCDEFGHIJKLMNOPQRSTUVWXYZ"
_LOWER = "abcdefghijklmnopqrstuvwxyz"
_DIGITS = "0123456789"
_ALNUM = _UPPER + _LOWER + _DIGITS
_B64URL = _ALNUM + "-_"
_SECRET_CHARS = _ALNUM + "!@#$%^&*()-_=+"
# No "@" or ":" here: these end up inside URLs, where they would break the shape.
_AUTH_CHARS = _ALNUM + "!$%^&*()-_=+"
_B64 = _ALNUM + "+/"

MAX_SURROGATE_LEN = 256  # keeps the streaming hold-back window bounded


def _rand(rng: random.Random, alphabet: str, n: int) -> str:
    return "".join(rng.choice(alphabet) for _ in range(n))


def _email(rng: random.Random) -> str:
    first = rng.choice(FIRST_NAMES)
    last = rng.choice(LAST_NAMES)
    suffix = "" if rng.random() < 0.6 else str(rng.randint(1, 99))
    return "%s.%s%s@%s" % (first, last, suffix, rng.choice(FAKE_DOMAINS))


def _ipv4(rng: random.Random) -> str:
    return "10.%d.%d.%d" % (rng.randint(0, 254), rng.randint(0, 254), rng.randint(1, 254))


def _cn_mobile(rng: random.Random) -> str:
    return "1%d%s" % (rng.randint(3, 9), _rand(rng, _DIGITS, 9))


def _cn_id(rng: random.Random) -> str:
    body = "%06d%s%s%03d" % (
        rng.randint(110101, 659004),
        rng.choice(["19", "20"]),
        rng.choice(["%02d%02d%02d" % (rng.randint(60, 99), rng.randint(1, 12), rng.randint(1, 28)),
                    "%02d%02d%02d" % (rng.randint(0, 24), rng.randint(1, 12), rng.randint(1, 28))]),
        rng.randint(0, 999),
    )
    weights = [7, 9, 10, 5, 8, 4, 2, 1, 6, 3, 7, 9, 10, 5, 8, 4, 2]
    checks = "10X98765432"
    if len(body) != 17:
        body = body[:17].ljust(17, "0")
    total = sum(int(body[i]) * weights[i] for i in range(17))
    return body + checks[total % 11]


def _aws_key(rng: random.Random) -> str:
    return "AKIA" + _rand(rng, _UPPER + _DIGITS, 16)


def _github_token(rng: random.Random) -> str:
    return "ghp_" + _rand(rng, _ALNUM, 36)


def _jwt(rng: random.Random) -> str:
    def seg(n: int) -> str:
        return _rand(rng, _B64URL, n)
    return "eyJ%s.%s.%s" % (seg(21), seg(36), seg(43))


def _private_key(rng: random.Random) -> str:
    lines = [_rand(rng, _B64, 64) for _ in range(3)]
    return "-----BEGIN RSA PRIVATE KEY-----\n%s\n-----END RSA PRIVATE KEY-----" % "\n".join(lines)


def _basic_auth(rng: random.Random, value: str) -> str:
    scheme = value.split("://", 1)[0] if "://" in value else "https"
    return "%s://%s:%s@" % (scheme, rng.choice(USERNAMES), _rand(rng, _AUTH_CHARS, 12))


_KEYWORD_SPLIT = re.compile(r"^([^=:：]{1,40}[=:：]\s*)(.*)$", re.S)


def _secret_keyword(rng: random.Random, value: str) -> str:
    match = _KEYWORD_SPLIT.match(value)
    if not match:
        return _generic(rng, value)
    prefix, original = match.group(1), match.group(2)
    body = _rand(rng, _SECRET_CHARS, max(12, min(len(original) or 12, 40)))
    return prefix + body


def _generic(rng: random.Random, value: str) -> str:
    """Same length, same character class family, nothing reused from the value."""
    n = max(6, min(len(value), 64))
    if re.fullmatch(r"[A-Za-z0-9]+", value or ""):
        alphabet = _ALNUM
    elif re.fullmatch(r"[A-Za-z0-9._%+\-@]+", value or ""):
        alphabet = _ALNUM + "._-"
    else:
        alphabet = _SECRET_CHARS
    return _rand(rng, alphabet, n)


def _username(rng: random.Random) -> str:
    return rng.choice(USERNAMES)


_GENERATORS = {
    "EMAIL_ADDRESS": lambda rng, value: _email(rng),
    "EMAIL": lambda rng, value: _email(rng),
    "IPV4": lambda rng, value: _ipv4(rng),
    "CN_MOBILE": lambda rng, value: _cn_mobile(rng),
    "PHONE_NUMBER": lambda rng, value: _cn_mobile(rng),
    "CN_ID": lambda rng, value: _cn_id(rng),
    "AWS_KEY": lambda rng, value: _aws_key(rng),
    "GITHUB_TOKEN": lambda rng, value: _github_token(rng),
    "JWT_TOKEN": lambda rng, value: _jwt(rng),
    "PRIVATE_KEY": lambda rng, value: _private_key(rng),
    "BASIC_AUTH_URL": _basic_auth,
    "SECRET_KEYWORD": _secret_keyword,
    "PASSWORD": _secret_keyword,
    "USERNAME": lambda rng, value: _username(rng),
}


def make_surrogate(kind: str, value: str, rng: random.Random) -> str:
    """Return a realistic fake of the same shape as *value*."""
    generator = _GENERATORS.get((kind or "").upper())
    if generator is not None:
        try:
            fake = generator(rng, value)
            if fake and fake != value:
                return fake[:MAX_SURROGATE_LEN]
        except Exception:
            pass
    return _generic(rng, value)
